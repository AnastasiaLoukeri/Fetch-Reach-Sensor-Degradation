# Sensor Degradation Wrapper

class SensorDegradationWrapper(gym.ObservationWrapper):
    DEGRADATION_TYPES = ["none", "noise", "dropout", "stuck"]

    def __init__(self, env, degradation_type="none", severity=0.0,
                 affected_dims=None):
        super().__init__(env)
        assert degradation_type in self.DEGRADATION_TYPES
        assert 0.0 <= severity <= 1.0
        self.degradation_type = degradation_type
        self.severity         = severity
        self._obs_dim         = env.observation_space["observation"].shape[0]
        self.affected_dims    = affected_dims if affected_dims is not None \
                                else list(range(self._obs_dim))
        self._last_obs        = None

    def observation(self, obs):
        if self.degradation_type == "none" or self.severity == 0.0:
            self._last_obs = obs["observation"].copy()
            return obs
        corrupted = obs["observation"].copy()
        if self.degradation_type == "noise":
            noise = np.random.normal(0, self.severity * 2.0,
                                     size=len(self.affected_dims))
            corrupted[self.affected_dims] += noise
        elif self.degradation_type == "dropout":
            mask = np.random.random(len(self.affected_dims)) > self.severity
            corrupted[self.affected_dims] *= mask.astype(float)
        elif self.degradation_type == "stuck":
            if self._last_obs is not None:
                n_stuck    = int(self.severity * len(self.affected_dims))
                stuck_dims = self.affected_dims[:n_stuck]
                corrupted[stuck_dims] = self._last_obs[stuck_dims]
        self._last_obs         = corrupted.copy()
        obs["observation"]     = corrupted
        return obs

    def reset(self, **kwargs):
        self._last_obs = None
        return super().reset(**kwargs)


# Domain Randomization Wrapper

class DomainRandomizationWrapper(gym.Wrapper):
    """
    Κάθε φορά που γίνεται reset, επιλέγεται τυχαία:
      - degradation_type: none / noise / dropout / stuck
      - severity: uniform από [severity_min, severity_max]

    Αυτό αναγκάζει τον agent να μάθει robust policy
    που δουλεύει υπό οποιαδήποτε συνθήκη.
    """

    def __init__(self, env, severity_min=0.0, severity_max=0.8,
                 include_clean=True):
        super().__init__(env)
        self.severity_min  = severity_min
        self.severity_max  = severity_max
        self.include_clean = include_clean

        # Τύποι που θα χρησιμοποιηθούν κατά training
        self.types = ["noise", "dropout", "stuck"]
        if include_clean:
            # 30% clean episodes για να μην ξεχάσει το clean task
            self.types += ["none", "none"]

        self._obs_dim    = env.observation_space["observation"].shape[0]
        self._last_obs   = None
        self._cur_type   = "none"
        self._cur_sev    = 0.0

    def reset(self, **kwargs):
        # Τυχαία επιλογή βλάβης για το νέο episode
        self._cur_type = np.random.choice(self.types)
        if self._cur_type == "none":
            self._cur_sev = 0.0
        else:
            self._cur_sev = np.random.uniform(
                self.severity_min, self.severity_max)

        self._last_obs = None
        obs, info      = self.env.reset(**kwargs)
        return self._corrupt(obs), info

    def step(self, action):
        obs, reward, terminated, truncated, info = self.env.step(action)
        return self._corrupt(obs), reward, terminated, truncated, info

    def _corrupt(self, obs):
        if self._cur_type == "none" or self._cur_sev == 0.0:
            self._last_obs = obs["observation"].copy()
            return obs

        corrupted = obs["observation"].copy()
        dims      = list(range(self._obs_dim))

        if self._cur_type == "noise":
            corrupted[dims] += np.random.normal(
                0, self._cur_sev * 2.0, size=len(dims))
        elif self._cur_type == "dropout":
            mask = np.random.random(len(dims)) > self._cur_sev
            corrupted[dims] *= mask.astype(float)
        elif self._cur_type == "stuck":
            if self._last_obs is not None:
                n_stuck = int(self._cur_sev * len(dims))
                corrupted[dims[:n_stuck]] = self._last_obs[dims[:n_stuck]]

        self._last_obs     = corrupted.copy()
        obs["observation"] = corrupted
        return obs


class TrainingCallback(BaseCallback):
    def __init__(self, log_interval=5000, verbose=0):
        super().__init__(verbose)
        self.log_interval    = log_interval
        self.timesteps       = []
        self.success_rates   = []
        self.episode_rewards = []
        self._ep_rewards     = []

    def _on_step(self) -> bool:
        for info in self.locals.get("infos", []):
            if "episode" in info:
                self._ep_rewards.append(info["episode"]["r"])

        if self.num_timesteps % self.log_interval == 0:
            infos     = self.locals.get("infos", [])
            successes = [i.get("is_success", 0) for i in infos]
            sr        = np.mean(successes) if successes else 0.0
            mr        = np.mean(self._ep_rewards[-20:]) \
                        if self._ep_rewards else 0.0

            self.timesteps.append(self.num_timesteps)
            self.success_rates.append(sr)
            self.episode_rewards.append(mr)

            if self.verbose > 0:
                print(f"  Step {self.num_timesteps:>7} | "
                      f"Success: {sr:.2f} | Reward: {mr:.2f}")
        return True


def train_adversarial():
    os.makedirs("models", exist_ok=True)
    os.makedirs("logs",   exist_ok=True)

    print("Adversarial Training (Domain Randomization) \n")
    print(f"Training for {TOTAL_STEPS:,} steps with random sensor degradation...")

    def make_env():
        def _init():
            env = gym.make("FetchReach-v4")
            env = DomainRandomizationWrapper(
                env,
                severity_min=0.0,
                severity_max=0.8,
                include_clean=True
            )
            env = Monitor(env)
            env.reset(seed=SEED)
            return env
        return _init

    vec_env = DummyVecEnv([make_env()])

    model = SAC(
        policy          = "MultiInputPolicy",
        env             = vec_env,
        learning_rate   = 1e-3,
        buffer_size     = 1_000_000,
        learning_starts = 1_000,
        batch_size      = 256,
        tau             = 0.005,
        gamma           = 0.95,
        train_freq      = 1,
        gradient_steps  = 1,
        policy_kwargs   = dict(net_arch=[256, 256]),
        verbose         = 0,
        seed            = SEED,
    )

    callback = TrainingCallback(log_interval=LOG_INTERVAL, verbose=1)
    model.learn(total_timesteps=TOTAL_STEPS, callback=callback)
    model.save(SAVE_PATH)
    print(f"\nModel saved to {SAVE_PATH}.zip")

    return model, callback



# Evaluate agent under degradation

def evaluate_model(model, degradation_types, severities, n_episodes=20):
    results = {d: {"severity": [], "success_rate": []}
               for d in degradation_types}

    for dtype in degradation_types:
        print(f"\n--- {dtype.upper()} ---")
        for severity in severities:
            env = SensorDegradationWrapper(
                gym.make("FetchReach-v4"),
                degradation_type=dtype,
                severity=severity
            )
            successes = []
            for _ in range(n_episodes):
                obs, _ = env.reset()
                done   = False
                while not done:
                    action, _ = model.predict(obs, deterministic=True)
                    obs, _, terminated, truncated, info = env.step(action)
                    done = terminated or truncated
                successes.append(info.get("is_success", 0))
            env.close()

            sr = float(np.mean(successes))
            results[dtype]["severity"].append(severity)
            results[dtype]["success_rate"].append(sr)
            print(f"  Severity {severity:.1f} | Success: {sr:.2f}")

    return results



def plot_final_comparison(baseline_path, adversarial_model,
                          degradation_types, severities):

    print("\n Final Comparison\n")

    vec_env       = DummyVecEnv([lambda: Monitor(gym.make("FetchReach-v4"))])
    baseline      = SAC.load(baseline_path, env=vec_env)

    print("Evaluating BASELINE...")
    results_b = evaluate_model(baseline, degradation_types,
                                severities, n_episodes=20)

    print("\nEvaluating ours...")
    results_a = evaluate_model(adversarial_model, degradation_types,
                                severities, n_episodes=20)

    # Plot
    n    = len(degradation_types)
    fig, axes = plt.subplots(1, n, figsize=(6*n, 4), sharey=True)
    if n == 1:
        axes = [axes]

    for ax, dtype in zip(axes, degradation_types):
        ax.plot(results_b[dtype]["severity"],
                results_b[dtype]["success_rate"],
                color="#888780", linewidth=2, marker="o",
                markersize=5, label="Baseline SAC")
        ax.plot(results_a[dtype]["severity"],
                results_a[dtype]["success_rate"],
                color="#1D9E75", linewidth=2, marker="o",
                markersize=5, label="Adversarial SAC (ours)")
        ax.set_title(f"{dtype} degradation")
        ax.set_xlabel("Severity")
        ax.set_ylabel("Success rate")
        ax.set_ylim(-0.05, 1.10)
        ax.legend(fontsize=9)
        ax.grid(True, alpha=0.3)
        ax.axhline(y=1.0, color="green", linestyle="--", alpha=0.3)

    plt.suptitle(
        "Baseline SAC vs Robust-Trained SAC under Sensor Degradation",
        fontsize=12)
    plt.tight_layout()
    plt.savefig("logs/final_comparison.png", dpi=150, bbox_inches="tight")
    print("\nSaved: logs/final_comparison.png")
    plt.show()

    # Summary table
    print("\n Summary Table ")
    print(f"{'Degradation':<12} {'Severity':<10} "
          f"{'Baseline':>10} {'Adversarial':>12} {'Δ':>8}")
    print("-" * 56)
    for dtype in degradation_types:
        for sev, sr_b, sr_a in zip(
            results_b[dtype]["severity"],
            results_b[dtype]["success_rate"],
            results_a[dtype]["success_rate"]
        ):
            delta = sr_a - sr_b
            print(f"{dtype:<12} {sev:<10.1f} "
                  f"{sr_b:>10.3f} {sr_a:>12.3f} {delta:>+8.3f}")

    return results_b, results_a



